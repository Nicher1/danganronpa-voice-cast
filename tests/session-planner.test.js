const assert=require('node:assert/strict');
const P=require('../session-planner');
const now=Date.parse('2026-10-21T16:00Z');
assert.equal(P.fresh().sessions[0].startAt,'2026-10-21T17:45:00.000Z');
assert.equal(P.instant('2026-10-26','19:00'),'2026-10-26T18:00:00.000Z');
assert.throws(()=>P.instant('2026-03-29','02:30'),/does not exist/);
assert.equal(P.instant('2026-10-25','02:30'),'2026-10-25T00:30:00.000Z');
let s=P.fresh(),start=Date.parse(s.sessions[0].startAt);
assert.equal(P.current(s,start-1),null);
assert.equal(P.current(s,start).id,'session-2026-10-21');
assert.equal(P.current(s,start+10*P.HOUR),null);
P.change(s,'break',{},start+P.HOUR);
P.change(s,'resume',{},start+2*P.HOUR);
P.change(s,'end',{},start+3*P.HOUR);
assert.deepEqual(P.duration(s.sessions[0],start+5*P.HOUR),{total:3*P.HOUR,breaks:P.HOUR,play:2*P.HOUR});
assert.equal(P.current(s,start+4*P.HOUR),null);
assert.equal(P.pollWeek(s,start+4*P.HOUR),'2026-10-26');
assert.throws(()=>P.change(s,'vote',{date:'2026-10-27',actorId:'a',available:true},now),/Tuesday/);
P.change(s,'schedule',{date:'2026-10-21',time:'15:00'},now); // same day past is permitted
assert.throws(()=>P.change(s,'schedule',{date:'2026-10-20',time:'15:00'},now));
const actors=[{id:s.hostActorId},{id:'b'},{id:'c'},{id:'d'}];
s=P.fresh();
for(const a of actors.slice(0,3))P.change(s,'vote',{date:'2026-10-30',actorId:a.id,available:true,offset:0},now);
P.change(s,'vote',{date:'2026-10-30',actorId:'b',available:true,offset:15},now);
assert.equal(P.suggestion(s,'2026-10-30',actors),15);
P.reconcile(s,actors,now); assert.equal(s.notices.length,1);
P.reconcile(s,actors,now); assert.equal(s.notices.length,1);
P.change(s,'vote',{date:'2026-10-30',actorId:'d',available:true,offset:0},now);
P.reconcile(s,actors,now); assert.equal(s.notices.length,2);
P.change(s,'schedule',{date:'2026-10-30',time:'19:15'},now);
assert.equal(s.votes['2026-10-30'].b.offset,0);
assert.equal(s.votes['2026-10-30'].c.offset,-15);
assert.equal(P.pollWeek(s,now,true),'2026-10-26'); // earliest upcoming is today's session
const auto=P.fresh();auto.votes=structuredClone(s.votes);auto.times={'2026-10-30':'19:15'};
const deadline=Date.parse(P.instant('2026-10-30','19:15'))-48*P.HOUR;
P.reconcile(auto,actors,deadline-1);assert.equal(auto.sessions.length,1);
P.reconcile(auto,actors,deadline);assert.equal(auto.sessions.length,2);
P.reconcile(auto,actors,deadline);assert.equal(auto.sessions.length,2);
console.log('Schedule timezone/DST, same-day testing, breaks, voting, time rebasing, notification deduplication and 48h selection passed.');
